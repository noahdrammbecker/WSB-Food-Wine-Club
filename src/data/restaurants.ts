export function getAverageRating(restaurantId: string): number {
  const restaurantReviews = reviews.filter(r => r.restaurantId === restaurantId);
  if (restaurantReviews.length === 0) return 0;
  const sum = restaurantReviews.reduce((acc, r) => acc + r.rating, 0);
  return Math.round((sum / restaurantReviews.length) * 10) / 10;
}

export function getReviewCount(restaurantId: string): number {
  return reviews.filter(r => r.restaurantId === restaurantId).length;
}

export function getRestaurantReviews(restaurantId: string): Review[] {
  return reviews.filter(r => r.restaurantId === restaurantId);
}

export function getRestaurantBySlug(slug: string): Restaurant | undefined {
  return restaurants.find(r => r.slug === slug);
}

export function getUpcomingEvents(): ClubEvent[] {
  return events
    .filter(e => new Date(e.date) >= new Date())
    .sort((a, b) => new Date(a.date).getTime() - new Date(b.date).getTime());
}
